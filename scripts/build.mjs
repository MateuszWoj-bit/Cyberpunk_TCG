import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const database = JSON.parse(read('cards.json'));
const limited = JSON.parse(read('limited.json'));
const market = JSON.parse(read('market.json'));
const fail = message => { throw new Error(message); };
if (database.count !== database.cards.length) fail('Niezgodny licznik kart.');
for (const key of ['id', 'slug', 'display_name']) {
  const values = database.cards.map(card => card[key]);
  if (values.some(value => !value) || new Set(values).size !== values.length) fail(`Brak lub duplikat ${key}.`);
}
const slugs = new Set(database.cards.map(card => card.slug));
const grades = new Set(['S', 'A+', 'A', 'A−', 'B+']);
const categories = new Set(['bomb', 'foundation', 'curve', 'legend', 'situational', 'caution']);
for (const [slug, rating] of Object.entries(limited.cards)) {
  if (!slugs.has(slug)) fail(`Nieznana karta w ocenach: ${slug}`);
  if (!categories.has(rating.category) || !rating.note || (rating.grade && !grades.has(rating.grade))) fail(`Niepoprawna ocena: ${slug}`);
}
for (const pair of limited.synergies) {
  if (!pair.note || pair.cards.some(slug => !slugs.has(slug))) fail('Niepoprawna synergia.');
}
for (const [slug, entry] of Object.entries(market.cards)) {
  const card = database.cards.find(card => card.slug === slug);
  const printing = card?.printings.find(p => p.rarity === entry.rarity && p.set.code === entry.set && p.collector_number === entry.number);
  if (!printing) fail(`Nie znaleziono wydania kolekcjonerskiego: ${slug}`);
  if (entry.sources.some(id => !market.sources.some(source => source.id === id))) fail(`Nieznane źródło: ${slug}`);
  entry.printing_id = printing.id;
}
for (const card of database.cards) {
  if (!card.name || !card.color || !card.card_type || !Array.isArray(card.printings)) fail(`Niekompletna karta: ${card.slug}`);
  if (!/^images\/[a-z0-9-]+\.webp$/.test(card.local_image)) fail(`Niepoprawna ścieżka: ${card.slug}`);
  const image = fs.readFileSync(path.join(root, card.local_image));
  if (image.toString('ascii', 0, 4) !== 'RIFF' || image.toString('ascii', 8, 12) !== 'WEBP') fail(`Niepoprawny WebP: ${card.slug}`);
  if (!card.printings.some(printing => printing.id === card.selected_printing_id)) fail(`Brak wybranego wydania: ${card.slug}`);
}
// A classic script keeps file:// support: no fetch, server or external dependency.
const data = '// Generated by node scripts/build.mjs. Edit cards.json, limited.json and market.json.\nwindow.CATALOG_DATA = ' + JSON.stringify({ ...database, limited, market }).replaceAll('<', '\\u003c') + ';\n';
const fields = ['id', 'slug', 'display_name', 'name', 'subname', 'color', 'card_type', 'cost', 'power', 'ram', 'is_eddiable', 'rarity', 'print_number', 'rules_text', 'legality', 'source_page', 'local_image', 'limited_grade', 'limited_category', 'limited_note'];
const cell = value => '"' + String(value ?? '').replaceAll('"', '""') + '"';
const csv = '\ufeff' + fields.join(',') + '\r\n' + database.cards.map(card => {
  const rating = limited.cards[card.slug];
  const row = { ...card, limited_grade: rating?.grade ? rating.grade + (rating.conditional ? ' warunkowe' : '') : '', limited_category: rating?.category, limited_note: rating?.note };
  return fields.map(key => cell(row[key])).join(',');
}).join('\r\n') + '\r\n';
for (const [name, content] of [['gallery.html', read('gallery.template.html')], ['catalog-data.js', data], ['cards.csv', csv]]) {
  if (process.argv.includes('--check')) {
    if (read(name) !== content) fail(`Nieaktualny plik ${name}. Uruchom npm run build.`);
  } else fs.writeFileSync(path.join(root, name), content, 'utf8');
}
console.log(`OK: ${database.cards.length} kart, ${Object.keys(limited.cards).length} ocen/opisów limited, komplet grafik; eksporty ${process.argv.includes('--check') ? 'zgodne' : 'wygenerowane'}.`);
